// Minimal CSV parser for the fitDad admin bulk-import (see app/admin/fitdad).
// Deliberately hand-rolled instead of pulling in a library: the only other
// candidate for this job (the `xlsx` npm package) is stuck on a version with
// two unpatched high-severity CVEs (prototype pollution + ReDoS — SheetJS
// stopped publishing fixed builds to npm), so plain CSV (which Excel opens
// and saves natively via "Save As") avoids that dependency entirely.
// Handles quoted fields (with escaped "" and embedded commas/newlines).
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else inQuotes = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.some((f) => f.trim() !== "")) rows.push(row);
      row = [];
    } else {
      field += c;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    if (row.some((f) => f.trim() !== "")) rows.push(row);
  }
  return rows;
}
